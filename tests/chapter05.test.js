ok("C2E/E2C/listening cover all 22 words",AUTH_WORDS.every(w=>{const en=words.find(v=>v.hanzi===w).english;return q("vocab_c2e").some(x=>x.hanzi===w)&&q("vocab_e2c").some(x=>x.english===en)&&q("listening").some(x=>x.hanzi===w);}));
