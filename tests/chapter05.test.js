ok("chapter 5 title from source",ch.title==="今天我休息 I'm off today");
const words=T.vocabOf(ch.id);
ok("22 vocab items = exact source set",words.length===22&&words.every(w=>AUTH_WORDS.includes(w.hanzi))&&AUTH_WORDS.every(w=>words.some(v=>v.hanzi===w)));
