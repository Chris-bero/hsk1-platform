ok("71 unique source sentences",sents.length===71,sents.length);
ok("no duplicate hanzi",new Set(sents.map(s=>s.hanzi)).size===71);
ok("7 source-translated sentences",sents.filter(s=>s.english).length===7,sents.filter(s=>s.english).length);
ok("every sentence carries pinyin (17 source / 54 requested)",sents.every(s=>s.pinyin)&&sents.filter(s=>s.pinyinProvenance==="source").length===17&&sents.filter(s=>s.pinyinProvenance==="instructor-requested").length===54);
