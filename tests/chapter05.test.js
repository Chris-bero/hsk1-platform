ok("chapters 1-4 still intact",["ch01-fltrp-lesson1","ch02-fltrp-lesson2","ch03-fltrp-lesson3","ch04-fltrp-lesson4"].every(b=>{const c=T.DB.chapters.find(c=>c.bundleCode===b);return c&&c.status==="ready";}));
console.log("\nCOVERAGE ch5: "+JSON.stringify(ch.validation.gen.byType));
