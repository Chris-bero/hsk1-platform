fs.writeFileSync('/tmp/app_ch3.js',src);
const T=require('/tmp/app_ch3.js');
let pass=0,fail=0;
const ok=(n,c,i="")=>{c?(pass++,console.log("PASS",n)):(fail++,console.log("FAIL",n,i));};
const AUTH_WORDS=["人","的","中国","法国","中文","她","这","谁","女朋友","哪","国","泰国","喂","姐姐","工作","还","忙","吗","对","太","我们","想"];
