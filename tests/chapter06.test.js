fs.writeFileSync('/tmp/app_ch6.js',src);
const T=require('/tmp/app_ch6.js');
let pass=0,fail=0;
const ok=(n,c,i="")=>{c?(pass++,console.log("PASS",n)):(fail++,console.log("FAIL",n,i));};
const AUTH_WORDS=["手机","电话","号","明天","去","哪儿","想","超市","买","东西","些","牛奶","吃","晚饭","那边","包子","非常","好吃","米饭","怎么","坐","出租车","西安饭店"];
