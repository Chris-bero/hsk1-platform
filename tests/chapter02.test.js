require('./domstub.js');
const fs=require('fs');
let src=fs.readFileSync('/tmp/app.js','utf8').replace(/^"use strict";/,'');
src+="\nmodule.exports={ensureCurriculumImported,vocabOf,sentencesOf,questionsOf,get DB(){return DB},CURRICULUM_BUNDLE};";
fs.writeFileSync('/tmp/app_ch2.js',src);
const T=require('/tmp/app_ch2.js');
let pass=0,fail=0;
const ok=(n,c,i="")=>{c?(pass++,console.log("PASS",n)):(fail++,console.log("FAIL",n,i));};

const AUTH_WORDS=["请问","你","叫","什么","名字","我","不","是","对不起","没关系","没事","很","高兴","认识","也"];
const AUTH_TRANSLATED=["我叫李文","在教室里，王一飞在认识学生。","在校园里，陈天中和白家月打招呼时认错了人。","在校园里，李文和白家月第一次相遇。","主语+谓语+宾语。","例如：我（主语）叫（谓语）陈天中（宾语）。","七加一，再减一，加完减完等于几？","加完减完还是七。"];

ok("chapter 2 bundle embedded",T.CURRICULUM_BUNDLE.some(b=>b.bundleCode==="ch02-fltrp-lesson2"));
const ch=T.DB.chapters.find(c=>c.bundleCode==="ch02-fltrp-lesson2");
ok("chapter 2 imported at boot",!!ch);
ok("chapter 2 status Ready",ch&&ch.status==="ready",ch&&ch.status);
ok("chapter 2 title from source",ch.title==="我叫李文 My name is Li Wen");
const words=T.vocabOf(ch.id);
ok("15 vocab items = exact source set",words.length===15&&words.every(w=>AUTH_WORDS.includes(w.hanzi))&&AUTH_WORDS.every(w=>words.some(v=>v.hanzi===w)));
ok("all vocab pinyin verified from source",words.every(w=>w.pinyin&&w.pinyinVerified));
const sents=T.sentencesOf(ch.id);
ok("44 unique source sentences",sents.length===44,sents.length);
ok("only the 8 source-translated sentences carry English",sents.filter(s=>s.english).length===8&&sents.filter(s=>s.english).every(s=>AUTH_TRANSLATED.includes(s.hanzi)));
const q=t=>T.questionsOf(ch.id,t);
ok("C2E/E2C/listening cover all 15 words",AUTH_WORDS.every(w=>{const en=words.find(v=>v.hanzi===w).english;return q("vocab_c2e").some(x=>x.hanzi===w)&&q("vocab_e2c").some(x=>x.english===en)&&q("listening").some(x=>x.hanzi===w);}));
ok("sent_e2c = 8 translated prompts, 4 opts, 1 key",q("sent_e2c").length===8&&q("sent_e2c").every(x=>x.english&&x.options.length===4&&x.options.filter(o=>o.correct).length===1));
ok("sent_c2e = 8 with 4 English opts",q("sent_c2e").length===8&&q("sent_c2e").every(x=>x.options.length===4&&x.options.filter(o=>o.correct).length===1));
ok("all 44 sentences carry pinyin (13 source + 31 requested)",sents.every(s=>s.pinyin)&&sents.filter(s=>s.pinyinProvenance==="source").length===13);
ok("Sentence Builder removed per instructor request",q("builder").length===0);
ok("cloze capped at 15 per chapter & blanks never punctuation",q("cloze").length===15&&q("cloze").every(x=>!/^[،。！？、؛：,.!?…—+＋-]$/.test(x.segments[x.blankIndex])));
ok("cloze spreads over 15 distinct source sentences",new Set(q("cloze").map(x=>x.sentenceId)).size===15);
ok("cloze key equals removed source segment",q("cloze").every(x=>{const s=T.DB.sentences.find(s=>s.id===x.sentenceId);return x.options.find(o=>o.correct).hanzi===s.segments[x.blankIndex];}));
ok("every MCQ exactly one correct option",T.questionsOf(ch.id).filter(x=>x.options).every(x=>x.options.filter(o=>o.correct).length===1));
ok("every question traces to a source item",T.questionsOf(ch.id).every(x=>(x.wordId&&words.some(w=>w.id===x.wordId))||(x.sentenceId&&sents.some(s=>s.id===x.sentenceId))));
ok("validation: 0 blocking issues, 0 flagged",ch.validation.ok&&ch.validation.issues.length===0&&ch.validation.flagged===0,JSON.stringify(ch.validation.issues));
ok("chapter 1 still intact",!!T.DB.chapters.find(c=>c.bundleCode==="ch01-fltrp-lesson1"&&c.status==="ready"));
console.log("\nCOVERAGE ch2: "+JSON.stringify(ch.validation.gen.byType));
console.log("===== chapter02: "+pass+" passed, "+fail+" failed =====");
process.exit(fail?1:0);
